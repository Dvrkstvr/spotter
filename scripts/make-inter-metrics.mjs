/**
 * Writes src/data/inter-metrics.ts — Inter's advance widths, measured from the
 * font files the app actually loads.
 *
 * The share card is drawn in SVG, and SVG has no layout: a name is not
 * ellipsized and a line of sets does not wrap unless something measured it
 * first. Guessing an average character width would be wrong in exactly the
 * places that matter — a German exercise name is long, and `W` is three times
 * `i`. So the widths are read out of `hmtx` for the two weights `font`
 * declares, for the characters a card can plausibly contain. Kerning is left
 * out; it moves a line by a pixel or two, which the card's margins absorb.
 *
 *     npm run metrics
 *
 * Rerun it if the Inter package changes. The output is generated — never edit
 * it by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = {
  regular: 'node_modules/@expo-google-fonts/inter/400Regular/Inter_400Regular.ttf',
  heading: 'node_modules/@expo-google-fonts/inter/500Medium/Inter_500Medium.ttf',
};

/**
 * Printable ASCII, Latin-1 (umlauts, ß, ×, ·) and the few typographic marks the
 * app's copy uses. Anything else falls back to the font's own average.
 */
const CHARS = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)),
  ...Array.from({ length: 96 }, (_, i) => String.fromCharCode(0xa0 + i)),
  '—',
  '–',
  '↳',
  '›',
  '‹',
  '…',
  '’',
  '‘',
  '“',
  '”',
  '„',
  '•',
  '½',
  '¼',
  '¾',
];

function tables(buf) {
  const n = buf.readUInt16BE(4);
  const out = {};
  for (let i = 0; i < n; i++) {
    const at = 12 + i * 16;
    out[buf.toString('latin1', at, at + 4)] = buf.readUInt32BE(at + 8);
  }
  return out;
}

/** Unicode → glyph id, from the first format 4 or 12 subtable found. */
function cmap(buf, off) {
  const n = buf.readUInt16BE(off + 2);
  for (let i = 0; i < n; i++) {
    const sub = off + buf.readUInt32BE(off + 4 + i * 8 + 4);
    const format = buf.readUInt16BE(sub);
    if (format === 12) {
      const groups = buf.readUInt32BE(sub + 12);
      return (cp) => {
        for (let g = 0; g < groups; g++) {
          const at = sub + 16 + g * 12;
          const start = buf.readUInt32BE(at);
          const end = buf.readUInt32BE(at + 4);
          if (cp >= start && cp <= end) return buf.readUInt32BE(at + 8) + (cp - start);
        }
        return 0;
      };
    }
    if (format === 4) {
      const segs = buf.readUInt16BE(sub + 6) / 2;
      const ends = sub + 14;
      const starts = ends + segs * 2 + 2;
      const deltas = starts + segs * 2;
      const ranges = deltas + segs * 2;
      return (cp) => {
        for (let s = 0; s < segs; s++) {
          if (cp > buf.readUInt16BE(ends + s * 2)) continue;
          const start = buf.readUInt16BE(starts + s * 2);
          if (cp < start) return 0;
          const delta = buf.readInt16BE(deltas + s * 2);
          const range = buf.readUInt16BE(ranges + s * 2);
          if (!range) return (cp + delta) & 0xffff;
          const g = buf.readUInt16BE(ranges + s * 2 + range + (cp - start) * 2);
          return g ? (g + delta) & 0xffff : 0;
        }
        return 0;
      };
    }
  }
  throw new Error('no usable cmap subtable');
}

function measure(path) {
  const buf = readFileSync(join(root, path));
  const t = tables(buf);
  const upm = buf.readUInt16BE(t.head + 18);
  const metrics = buf.readUInt16BE(t.hhea + 34);
  const glyph = cmap(buf, t.cmap);
  const advance = (g) => buf.readUInt16BE(t.hmtx + Math.min(g, metrics - 1) * 4);
  const widths = {};
  let sum = 0;
  let count = 0;
  for (const ch of CHARS) {
    const g = glyph(ch.codePointAt(0));
    if (!g) continue;
    // Thousandths of an em, rounded: finer than any card can draw.
    const w = Math.round((advance(g) / upm) * 1000);
    widths[ch] = w;
    if (/[a-z]/.test(ch)) {
      sum += w;
      count++;
    }
  }
  return { widths, fallback: Math.round(sum / count) };
}

const out = Object.fromEntries(Object.entries(FONTS).map(([k, p]) => [k, measure(p)]));

const body = (m) =>
  `{\n    fallback: ${m.fallback},\n    widths: ${JSON.stringify(m.widths)},\n  }`;

writeFileSync(
  join(root, 'src/data/inter-metrics.ts'),
  `/**
 * Inter's advance widths in thousandths of an em — GENERATED by
 * scripts/make-inter-metrics.mjs from the font files the app loads. Do not
 * edit; rerun \`npm run metrics\`.
 */
export const INTER: Record<'regular' | 'heading', { fallback: number; widths: Record<string, number> }> = {
  regular: ${body(out.regular)},
  heading: ${body(out.heading)},
};
`
);
console.log(`inter-metrics: ${Object.keys(out.regular.widths).length} characters per weight`);
